'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const {indexedDB}=require('fake-indexeddb');
const {Store}=require('../dist/progress.js');
const core=require('../dist/cloud-core.js');
global.CETCloudCore=core;
global.localStorage={length:0,getItem(){return null;},setItem(){},removeItem(){}};
global.addEventListener=()=>{};
global.BroadcastChannel=undefined;
test('IndexedDB retains offline edits across reload and rebases edits made during sync',async()=>{
 const db=await new Promise((resolve,reject)=>{const q=indexedDB.open('cloud-test',1);q.onupgradeneeded=()=>q.result.createObjectStore('kv');q.onerror=reject;q.onsuccess=()=>resolve(q.result);});
 let local={...core.state(),theme:'dark',inkNotes:{p:[{id:'local-ink'}]}}, errors=[];
 const make=()=>new Store(db,()=>local,x=>{local=x;},e=>errors.push(e));
 let s=make();await s.init(local);
 local={...local,answers:{q1:'A'}};await s.save();
 assert.equal(await s.cloudMeta(),undefined);
 const owner=crypto.randomUUID();await s.enableCloud(owner);
 const pending=(await s.cloudMeta()).outbox;
 assert.equal(pending.length,1);assert.equal(pending[0].seed.answers.q1,'A');assert.equal(pending[0].seed.inkNotes,undefined);
 local={...local,answers:{q2:'C'},studySeconds:15};await s.save();
 s=make();await s.init(local);
 assert.equal((await s.cloudMeta()).outbox.length,2);
 const remote={state:core.state({answers:{q1:'A',q3:'B'},studySeconds:20}),deleted:{}};
 await s.acceptCloud({owner,revision:1,ack:[pending[0].id],document:remote});
 assert.deepEqual(local.answers,{q2:'C',q3:'B'});assert.equal(local.studySeconds,35);assert.equal(local.theme,'dark');assert.equal(local.inkNotes.p[0].id,'local-ink');
 const op=(await s.cloudMeta()).outbox[0];core.apply(remote,op);
 await s.acceptCloud({owner,revision:2,ack:[op.id],document:remote});
 assert.equal((await s.cloudMeta()).outbox.length,0);assert.equal(local.studySeconds,35);
 await assert.rejects(s.enableCloud(crypto.randomUUID()),/已绑定/);
 assert.deepEqual(errors,[]);
 db.close();
});
